//! Adversarial region-end cases: each language's data must hide `}` from the
//! host splitter, and the balanced-brace negative control must fail them.
use meld_core::region_end_spec::{RegionEndSpec, ScannerKind};
use meld_core::scanners::{
    counted::CountedScanner, delimited::DelimitedScanner, heredoc::HeredocScanner,
    indent::IndentScanner, template::TemplateScanner,
};
use meld_core::splitter::{
    render, split, BalancedBraceScanner, EndScanner, RegionEnd, RegionKind, ScannerRegistry,
};
use std::sync::Arc;

fn find(src: &str, scanner: &dyn EndScanner) -> Option<RegionEnd> {
    let start = src.find('{').expect("block opener") + 1;
    scanner.find_region_end(src, start)
}

fn assert_end(src: &str, scanner: &dyn EndScanner) -> RegionEnd {
    let intended = src.rfind('}').expect("real closer");
    let end = find(src, scanner).unwrap_or_else(|| panic!("no end for {src:?}"));
    assert_eq!(end.body_end, intended, "wrong end in {src:?}");
    assert_eq!(end.full_end, intended + 1);
    assert_eq!(end.close_marker, "}");
    end
}

fn assert_generic_fails(src: &str) {
    let end = find(src, &BalancedBraceScanner);
    let intended = src.rfind('}').unwrap();
    assert_ne!(
        end.map(|e| e.body_end),
        Some(intended),
        "negative control unexpectedly passed: {src:?}"
    );
}

fn split_with(
    lang: &str,
    scanner: Arc<dyn EndScanner>,
    src: &str,
) -> meld_core::splitter::SplitDocument {
    let mut registry = ScannerRegistry::empty();
    registry.register([lang], scanner);
    let doc = split(src, &registry).unwrap_or_else(|e| panic!("split failed: {e}"));
    assert_eq!(render(&doc), src, "render changed source");
    doc
}

#[test]
fn ruby_heredoc_hides_a_brace_from_the_generic_scanner() {
    let src = "@ruby { html = <<~SQL\n  SELECT } FROM t\nSQL\nputs html }";
    assert_end(src, &HeredocScanner::ruby());
    assert_generic_fails(src);
    let doc = split_with("ruby", Arc::new(HeredocScanner::ruby()), src);
    let block = doc
        .regions
        .iter()
        .find(|r| r.kind == RegionKind::Block)
        .unwrap();
    assert!(block.body(src).contains("SELECT } FROM t"));
    assert_eq!(block.close_marker, "}");
}

#[test]
fn ruby_heredoc_variants_and_lookalikes() {
    for (opener, terminator) in [
        ("<<SQL", "SQL"),
        ("<<-SQL", "  SQL"),
        ("<<\"SQL\"", "SQL"),
        ("<<'SQL'", "SQL"),
    ] {
        let src =
            format!("@ruby {{ x = {opener}\n  SELECT }} FROM t\nSQLx\n{terminator}\nputs x }}");
        assert_end(&src, &HeredocScanner::ruby());
        assert_generic_fails(&src);
    }
}

#[test]
fn ruby_multiple_heredocs_use_fifo_order() {
    // Two openers on one line: both bodies begin on the next line, and each
    // terminator pops one heredoc in opener order.
    let src = "@ruby { a = <<A + <<B\n  first } line\nA\n  second } line\nB\nputs a, b }";
    assert_end(src, &HeredocScanner::ruby());
    assert_generic_fails(src);

    // Sequenced heredocs, as generated by research/composition/benchmark.py.
    let src = "@ruby { a = <<~A\n <a> } </a>\nA\n b = <<~B\n <b> } </b>\nB\nputs a, b }";
    assert_end(src, &HeredocScanner::ruby());
}

#[test]
fn shift_expression_is_not_a_heredoc_opener() {
    let src = "@ruby { x = flags<<mask; y = 1 }";
    assert_end(src, &HeredocScanner::ruby());
}

#[test]
fn python_triple_strings_and_dedents_hide_braces() {
    // A plain `"` inside the triple string makes the generic quote pairing
    // end on the wrong side of the hidden brace.
    let src = "@python { s = \"\"\"a \" } b\"\"\"; print(s) }";
    assert_end(src, &IndentScanner::python());
    assert_generic_fails(src);
    let doc = split_with("python", Arc::new(IndentScanner::python()), src);
    let block = doc
        .regions
        .iter()
        .find(|r| r.kind == RegionKind::Block)
        .unwrap();
    assert!(block.body(src).contains("a \" } b"));

    // A dedented dict literal must not be mistaken for the region end.
    let src = "@python {\n    d = {\"k\": 1}\n    print(d)\n}";
    assert_end(src, &IndentScanner::python());
}

#[test]
fn yaml_block_scalar_hides_a_brace() {
    let src = "@yaml { key: |\n  a } b\nnext: value\n}";
    assert_end(src, &IndentScanner::yaml());
    assert_generic_fails(src);
}

#[test]
fn lua_long_brackets_hide_a_brace() {
    let src = "@lua { local s = [==[ brace } data ]==]; print(s) }";
    assert_end(src, &DelimitedScanner::lua());
    assert_generic_fails(src);
}

#[test]
fn sql_dollar_quote_hides_a_brace() {
    let src = "@sql { SELECT $tag$ brace } data $tag$ AS x; }";
    assert_end(src, &DelimitedScanner::sql());
    assert_generic_fails(src);
}

#[test]
fn rust_raw_strings_and_nested_comments_hide_braces() {
    let src = "@rust { let s = r##\"a \"#} b\"##; /* outer /* } */ inner */ let x = 'a'; }";
    assert_end(src, &CountedScanner::rust());
    assert_generic_fails(src);

    // A Rust lifetime must not open a quote that swallows the real closer.
    let src = "@rust { let r: &'static str = \"x}\"; }";
    assert_end(src, &CountedScanner::rust());
}

#[test]
fn cpp_raw_and_r_raw_strings_hide_braces() {
    // Embedded `"` bytes make the generic quote rule end early; the counted
    // delimiter is the only reliable close marker here.
    let src = "@cpp { auto s = R\"tag(a \" brace })tag\"; }";
    assert_end(src, &CountedScanner::cpp());
    assert_generic_fails(src);
    let src = "@r { x <- r\"---(a \" })---\"; }";
    assert_end(src, &CountedScanner::r());
    assert_generic_fails(src);
}

#[test]
fn ocaml_and_haskell_nested_comments_hide_braces() {
    let src = "@ocaml { (* outer (* } *) inner *) let x = 1 }";
    assert_end(src, &CountedScanner::ocaml());
    assert_generic_fails(src);
    let src = "@haskell { {- outer {- } -} inner -} x = 1 }";
    assert_end(src, &CountedScanner::haskell());
    assert_generic_fails(src);
}

#[test]
fn javascript_template_interpolation_hides_braces() {
    let src = "@javascript { const t = `a ${ \"}\" } b`; console.log(t); }";
    assert_end(src, &TemplateScanner);
    // The Phase 1 backtick rule happens to cover the simple form; the nested
    // template is the real negative control.
    let nested = "@javascript { const t = `a ${ `inner } text` } b`; console.log(t); }";
    assert_end(nested, &TemplateScanner);
    assert_generic_fails(nested);
}

#[test]
fn php_and_bash_heredocs_hide_braces() {
    let src = "@php { $x = <<<'SQL'\n  } data\nSQL\n echo $x; }";
    assert_end(src, &HeredocScanner::php());
    assert_generic_fails(src);
    let src = "@bash { cat <<'EOF'\n} data\nEOF\n echo done }";
    assert_end(src, &HeredocScanner::bash());
    assert_generic_fails(src);
}

#[test]
fn raw_hash_delimiters_bypass_every_scanner() {
    let src = "@ruby#\" html = <<~SQL\n  } literal\nSQL\n \"# tail\n";
    // No scanner is registered at all: the raw delimiter still splits.
    let doc = split(src, &ScannerRegistry::empty()).unwrap();
    let block = doc
        .regions
        .iter()
        .find(|r| r.kind == RegionKind::Block)
        .unwrap();
    assert!(block.body(src).contains("} literal"));
    assert_eq!(block.close_marker, "\"#");
    assert_eq!(render(&doc), src);
}

#[test]
fn metadata_selects_a_builtin_and_never_executes_pack_code() {
    let toml = "schema = \"meld-region-end/1\"\nkind = \"heredoc\"\nfallback = \"brace\"\nhint = \"raw hash delimiters remain available\"\n[options]\ndialect = \"ruby\"\n";
    let spec = RegionEndSpec::parse(toml);
    assert_eq!(spec.kind, ScannerKind::Heredoc);
    assert_eq!(spec.hint, "raw hash delimiters remain available");
    let scanner = spec.scanner();
    let src = "@ruby { x = <<~SQL\n } data\nSQL\nputs x }";
    assert_end(src, scanner.as_ref());

    let wasm = RegionEndSpec::parse(
        "schema = \"meld-region-end/1\"\nkind = \"wasm\"\n[options]\nmodule = \"region_end.wat\"\n",
    );
    assert_eq!(wasm.kind, ScannerKind::Wasm);
    let src = "@ruby { x = <<~SQL\n } data\nSQL\nputs x }";
    assert!(find(src, wasm.scanner().as_ref()).is_some());
    // Brace fallback stops at the heredoc's data brace, not the real closer.
    assert_ne!(
        find(src, wasm.scanner().as_ref()).map(|e| e.body_end),
        Some(src.rfind('}').unwrap())
    );
}
