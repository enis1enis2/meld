#!/usr/bin/env python3
"""Add or refresh `library.toml` for checked-in Lang Packs.

JUDGMENT CALL: a Lang Library is a Lang Pack plus a small install manifest
(spec/libraries.md). Existing packs predate that manifest, so this tool derives
it from `pack.toml` instead of hand-editing 28 directories. It also refreshes
`checksums.sha256`; Ed25519 signing stays a separate, explicit step because the
private key must never live in the repository (project.md §9).
"""
from __future__ import annotations

import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import packtool  # noqa: E402

API = "meld-lang-library/1"
DEFAULT_VERSION = "0.1.0"
DEFAULT_PACKS = sorted(p for p in (ROOT / "packs").iterdir() if (p / "pack.toml").is_file())
DEFAULT_FIXTURE = ROOT / "tests" / "fixtures" / "pack-third-party"

NAMES = {
    "bash": "Bash", "c": "C", "cpp": "C++", "csharp": "C#", "css": "CSS",
    "dart": "Dart", "go": "Go", "haskell": "Haskell", "html": "HTML",
    "java": "Java", "javascript": "JavaScript", "json": "JSON", "lua": "Lua",
    "markdown": "Markdown", "ocaml": "OCaml", "php": "PHP", "python": "Python",
    "r": "R", "ruby": "Ruby", "rust": "Rust", "scala": "Scala",
    "solidity": "Solidity", "shell": "POSIX Shell", "sql": "SQL", "toml": "TOML",
    "tsx": "TSX", "typescript": "TypeScript", "yaml": "YAML", "zig": "Zig",
}

EXPORT_ORDER = (
    "pack.toml",
    "grammar/REFERENCE.md",
    "queries/highlights.scm",
    "queries/injections.scm",
    "region_end.toml",
    "region_end.wat",
    "region_end.sh",
    "runner.toml",
    "inline.toml",
    "lsp.toml",
    "formatter.toml",
    "toolchain.toml",
    "worker.sh",
    "README.md",
    "tests/feed.meld",
    "tests/conformance.json",
    "tests/run_conformance.py",
)


def toml_strings(values: list[str]) -> str:
    # This helper emits a complete TOML array because the template below does
    # not add brackets; gen_pack.py has the inverse helper for its own templates.
    return "[" + ", ".join(f'"{value}"' for value in values) + "]"


def ensure_version(pack_dir: Path, manifest: dict) -> str:
    version = manifest.get("version")
    if isinstance(version, str) and version:
        return version
    path = pack_dir / "pack.toml"
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines(keepends=True)
    for index, line in enumerate(lines):
        if line.startswith("id = "):
            lines.insert(index + 1, f'version = "{DEFAULT_VERSION}"\n')
            path.write_text("".join(lines), encoding="utf-8")
            print(f"added version to {path.relative_to(ROOT)}")
            break
    else:
        raise SystemExit(f"no id field in {path}")
    return DEFAULT_VERSION


def write_library(pack_dir: Path) -> None:
    path = pack_dir / "pack.toml"
    with path.open("rb") as handle:
        manifest = tomllib.load(handle)
    pack_id = manifest["id"]
    version = ensure_version(pack_dir, manifest)
    aliases = manifest.get("aliases") or []
    exports = [rel for rel in EXPORT_ORDER if (pack_dir / rel).is_file()]
    name = NAMES.get(pack_id, pack_id.title())
    text = (
        "# Generated by tools/make_libraries.py; edit pack.toml or rerun the tool.\n"
        "# JUDGMENT CALL: `exports` is the stable data surface an importer may rely on.\n"
        f'api = "{API}"\n'
        'kind = "lang"\n'
        f'id = "{pack_id}"\n'
        f'name = "{name}"\n'
        f'version = "{version}"\n'
        f"aliases = {toml_strings(aliases)}\n"
        f"exports = {toml_strings(exports)}\n"
    )
    (pack_dir / "library.toml").write_text(text, encoding="utf-8")
    packtool.write_checksums(pack_dir)
    print(f"library + checksums: {pack_dir.relative_to(ROOT)}")


def main() -> int:
    dirs = [Path(arg) for arg in sys.argv[1:]]
    if not dirs:
        dirs = DEFAULT_PACKS + ([DEFAULT_FIXTURE] if DEFAULT_FIXTURE.is_dir() else [])
    for pack_dir in dirs:
        if not pack_dir.is_absolute():
            pack_dir = ROOT / pack_dir
        if not (pack_dir / "pack.toml").is_file():
            raise SystemExit(f"not a pack directory: {pack_dir}")
        write_library(pack_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
